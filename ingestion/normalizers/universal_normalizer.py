# MAIN RECORD ROUTER
# ============================================================

def normalize_record(record):

    source_file = record.get(
        "source_file",
        ""
    )

    extension = record.get(
        "extension",
        ""
    ).lower()

    data = record.get(
        "data",
        {}
    )

    if not record.get(
        "success",
        False
    ):
        return None

    content = (
        data.get("content")
        if isinstance(data, dict)
        else data
    )

    data_type = (
        data.get("type", "")
        if isinstance(data, dict)
        else ""
    )

    source_upper = source_file.upper()

    # --------------------------------------------------------
    # NEVER INGEST EVALUATION MATERIAL
    # --------------------------------------------------------

    if source_upper.startswith(
        "14_EVALUATION_ONLY\\"
    ):
        return None

    # --------------------------------------------------------
    # CASE
    # --------------------------------------------------------

    if source_upper.startswith(
        "00_CASE_CONTEXT\\"
    ):
        return normalize_case_context(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # PERSON PROFILES
    # --------------------------------------------------------

    if (
        "\\PERSON_PROFILES\\"
        in source_upper
    ):
        return normalize_person(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # LOCATIONS - TXT
    # --------------------------------------------------------

    if (
        "\\03_LOCATIONS\\"
        in source_upper
        and "\\SITE_PLANS\\"
        in source_upper
    ):
        return normalize_location(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # LOCATIONS - GEOJSON
    # --------------------------------------------------------

    if extension == ".geojson":
        return normalize_geojson_locations(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # LOCATIONS - KML
    # --------------------------------------------------------

    if extension == ".kml":
        return normalize_kml_locations(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # CALL RECORDS
    # --------------------------------------------------------

    if (
        "\\CALL_RECORDS\\"
        in source_upper
    ):

        if isinstance(content, list):

            return [
                normalize_call(
                    source_file,
                    row,
                )
                for row in content
            ]

        return normalize_call(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # MESSAGES CSV
    # --------------------------------------------------------

    if source_upper.endswith(
        "MESSAGES.CSV"
    ):

        if isinstance(content, list):

            return [
                normalize_message(
                    source_file,
                    row,
                )
                for row in content
            ]

        return normalize_message(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # EMAIL
    # --------------------------------------------------------

    if extension == ".eml":
        return normalize_email(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # TRANSACTIONS
    # --------------------------------------------------------

    if (
        "\\TRANSACTION_EXPORTS\\"
        in source_upper
    ):

        if isinstance(content, list):

            return [
                normalize_transaction(
                    source_file,
                    row,
                )
                for row in content
            ]

        if isinstance(content, dict):

            transactions = content.get(
                "Transaction"
            )

            if isinstance(
                transactions,
                list,
            ):
                return [
                    normalize_transaction(
                        source_file,
                        row,
                    )
                    for row in transactions
                ]

            # Some extracted XML files
            # have an extra Transactions layer.

            transactions_container = content.get(
                "Transactions"
            )

            if isinstance(
                transactions_container,
                dict,
            ):

                transactions = (
                    transactions_container.get(
                        "Transaction"
                    )
                )

                if isinstance(
                    transactions,
                    list,
                ):
                    return [
                        normalize_transaction(
                            source_file,
                            row,
                        )
                        for row in transactions
                    ]

        return normalize_transaction(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # VEHICLE REGISTRY
    # --------------------------------------------------------

    if source_upper.endswith(
        "VEHICLE_REGISTRY.CSV"
    ):

        if isinstance(content, list):

            return [
                normalize_vehicle_registry(
                    source_file,
                    row,
                )
                for row in content
            ]

        return normalize_vehicle_registry(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # VEHICLE SIGHTINGS
    # --------------------------------------------------------

    if source_upper.endswith(
        "VEHICLE_SIGHTINGS.JSON"
    ):

        if isinstance(content, list):

            return [
                normalize_vehicle_sighting(
                    source_file,
                    row,
                )
                for row in content
            ]

        return normalize_vehicle_sighting(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # DEVICE EXTRACTION / GPS
    # --------------------------------------------------------

    if (
        "\\07_DEVICES\\"
        in source_upper
    ):
        return normalize_gps(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # GPS CSV
    # --------------------------------------------------------

    if source_upper.endswith(
        "GPS_POINTS.CSV"
    ):
        return normalize_gps_csv(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # ACCESS CONTROL
    # --------------------------------------------------------

    if (
        "\\09_ACCESS_SECURITY\\"
        in source_upper
    ):
        return normalize_access_log(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # CALENDAR / ICS
    # --------------------------------------------------------

    if extension == ".ics":
        return normalize_calendar_event(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # WITNESS MATERIAL
    # --------------------------------------------------------

    if (
        "\\02_WITNESS_MATERIAL\\"
        in source_upper
    ):
        return normalize_witness(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # FORENSICS
    # --------------------------------------------------------

    if (
        "\\10_FORENSICS\\"
        in source_upper
    ):
        return normalize_generic_document(
            source_file,
            content,
        )

    # --------------------------------------------------------
    # EVERYTHING ELSE
    # --------------------------------------------------------

    return normalize_generic_document(
        source_file,
        content,
    )


# ============================================================
# NORMALIZE COMPLETE FILE
# ============================================================

def normalize_file(
    input_path,
    output_path,
):

    with open(
        input_path,
        "r",
        encoding="utf-8",
    ) as f:

        records = json.load(f)

    normalized = []

    for record in records:

        try:

            result = normalize_record(
                record
            )

            for item in flatten(result):

                if item is not None:
                    normalized.append(item)

        except Exception as exc:

            normalized.append({
                "normalization_error": str(
                    exc
                ),
                "source_file": record.get(
                    "source_file"
                ),
            })

    output = {
        "metadata": {
            "source": str(
                input_path
            ),
            "record_count": len(
                normalized
            ),
            "evaluation_material_excluded": True,
        },
        "records": normalized,
    }

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(
        output_path,
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            output,
            f,
            indent=2,
            ensure_ascii=False,
        )

    print(
        f"Normalized records: "
        f"{len(normalized)}"
    )

    print(
        f"Saved to: {output_path}"
    )


