def make_gps_event(
    source_file,
    entity_id,
    point,
    device_id=None,
    device_type=None,
):
    return {
        "event": {
            "type": "MOVEMENT",
            "entity": entity_id,
            "event_time": point.get(
                "time"
            ),
            "description": (
                "Device location observation"
            ),
            "attributes": {
                "latitude": safe_float(
                    point.get("lat")
                ),
                "longitude": safe_float(
                    point.get("lon")
                ),
                "accuracy_m": safe_float(
                    point.get("accuracy_m")
                ),
                "device_id": device_id,
                "device_type": device_type,
                "point_id": point.get(
                    "point_id"
                ),
            },
        },
        "evidence": {
            "type": "GPS",
            "description": (
                "Extracted device location point"
            ),
            "base_confidence": 0.80,
            "attributes": point,
        },
        "source_file": source_file,
    }


def normalize_gps(
    source_file,
    content,
):
    if not isinstance(content, dict):
        return None

    entity_id = content.get(
        "entity_id"
    )

    artifacts = content.get(
        "artifacts",
        {}
    )

    points = artifacts.get(
        "location_points",
        []
    )

    results = []

    for point in points:

        if not isinstance(point, dict):
            continue

        results.append(
            make_gps_event(
                source_file,
                entity_id,
                point,
                content.get(
                    "device_id"
                ),
                content.get(
                    "device_type"
                ),
            )
        )

    return results


def normalize_gps_csv(
    source_file,
    content,
):
    if not isinstance(content, list):
        return None

    results = []

    for row in content:

        if not isinstance(row, dict):
            continue

        point = {
            "point_id": row.get(
                "point_id"
            ),
            "time": row.get(
                "timestamp"
            ),
            "lat": row.get(
                "lat"
            ),
            "lon": row.get(
                "lon"
            ),
            "accuracy_m": row.get(
                "accuracy_m"
            ),
        }

        results.append(
            make_gps_event(
                source_file,
                row.get("entity_id"),
                point,
            )
        )

    return results


