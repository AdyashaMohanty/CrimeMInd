# LOCATION
# ============================================================

def normalize_location(source_file, content):
    """
    Normalize location TXT files.

    Example:

        LOCATION
        L001
        Meridian House
        Type: mixed-use heritage property

    """

    if not isinstance(content, str):
        return None

    lines = [
        line.strip()
        for line in content.splitlines()
        if line.strip()
    ]

    location_id = None
    location_name = None
    location_type = None

    for line in lines:

        if line.startswith("L") and len(line) <= 10:
            location_id = line

        elif line.lower().startswith("type:"):
            location_type = line.split(
                ":",
                1
            )[1].strip()

    # Find location name.
    if location_id:
        try:
            index = lines.index(location_id)

            if index + 1 < len(lines):
                location_name = lines[index + 1]

        except ValueError:
            pass

    if not location_id:
        data = parse_key_value_text(content)

        location_id = data.get("id")
        location_name = data.get(
            "name",
            location_id,
        )

    if not location_id:
        return None

    return {
        "location": {
            "external_reference": location_id,
            "location_name": (
                location_name
                or location_id
            ),
            "location_type": location_type,
            "address": None,
            "latitude": None,
            "longitude": None,
            "attributes": {
                "source_format": "site_plan_text",
            },
        },
        "source_file": source_file,
    }


# ============================================================
# GEOJSON
# ============================================================

def normalize_geojson_locations(
    source_file,
    content,
):
    """
    Normalize GeoJSON location coordinates.

    Coordinates are stored as:

        longitude, latitude
    """

    if not isinstance(content, dict):
        return None

    features = content.get("features", [])

    results = []

    for feature in features:

        if not isinstance(feature, dict):
            continue

        properties = feature.get(
            "properties",
            {}
        )

        geometry = feature.get(
            "geometry",
            {}
        )

        location_id = properties.get(
            "location_id"
        )

        coordinates = geometry.get(
            "coordinates",
            []
        )

        if not location_id:
            continue

        longitude = None
        latitude = None

        if (
            isinstance(coordinates, list)
            and len(coordinates) >= 2
        ):
            longitude = safe_float(
                coordinates[0]
            )

            latitude = safe_float(
                coordinates[1]
            )

        results.append({
            "location_geometry": {
                "external_reference": location_id,
                "latitude": latitude,
                "longitude": longitude,
                "geometry_type": geometry.get(
                    "type"
                ),
            },
            "source_file": source_file,
        })

    return results


# ============================================================
# KML
# ============================================================

def normalize_kml_locations(
    source_file,
    content,
):
    """
    Normalize extracted KML places.

    Example:

        {
            "name": "L001",
            "coordinates": "85.82,20.29,0"
        }
    """

    if not isinstance(content, dict):
        return None

    places = content.get(
        "places",
        []
    )

    results = []

    for place in places:

        if not isinstance(place, dict):
            continue

        location_id = place.get("name")

        coordinate_string = place.get(
            "coordinates",
            ""
        )

        parts = coordinate_string.split(",")

        longitude = None
        latitude = None

        if len(parts) >= 2:

            longitude = safe_float(
                parts[0]
            )

            latitude = safe_float(
                parts[1]
            )

        if not location_id:
            continue

        results.append({
            "location_geometry": {
                "external_reference": location_id,
                "latitude": latitude,
                "longitude": longitude,
                "geometry_type": "Point",
            },
            "source_file": source_file,
        })

    return results


