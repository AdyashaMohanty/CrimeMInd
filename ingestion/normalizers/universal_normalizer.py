# ACCESS LOG
# ============================================================

def normalize_access_log(
    source_file,
    content,
):
    """
    Convert each access-log line into an actual event.

    Example:

        2026-08-18 20:54:11 ACCESS L001 EAST_DOOR P005 GRANTED

    """

    if not isinstance(content, str):
        return None

    results = []

    for line in content.splitlines():

        line = line.strip()

        if not line:
            continue

        parts = line.split()

        if len(parts) < 4:
            continue

        date_part = parts[0]
        time_part = parts[1]

        event_time = (
            f"{date_part}T{time_part}"
        )

        event_keyword = parts[2]

        location_id = (
            parts[3]
            if len(parts) > 3
            else None
        )

        remaining = parts[4:]

        entity_id = None

        for token in remaining:

            if (
                isinstance(token, str)
                and token.startswith("P")
                and token[1:].isdigit()
            ):
                entity_id = token
                break

        status = (
            remaining[-1]
            if remaining
            else None
        )

        results.append({
            "event": {
                "type": (
                    "ALARM"
                    if event_keyword == "ALARM"
                    else "ACCESS"
                ),
                "entity": entity_id,
                "event_time": event_time,
                "description": line,
                "attributes": {
                    "location_reference": location_id,
                    "event_keyword": event_keyword,
                    "status": status,
                    "raw_line": line,
                },
            },
            "evidence": {
                "type": "ACCESS_LOG",
                "description": line,
                "base_confidence": 0.82,
                "attributes": {
                    "location_reference": location_id,
                    "entity_reference": entity_id,
                    "raw_line": line,
                },
            },
            "source_file": source_file,
        })

    return results


