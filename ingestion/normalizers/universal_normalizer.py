def parse_key_value_text(text):
    """
    Convert simple extracted text such as:

        ID: P001
        Name: Arvind Malhotra
        Role: property owner

    into a dictionary.
    """

    result = {}

    if not isinstance(text, str):
        return result

    for line in text.splitlines():
        line = line.strip()

        if ":" not in line:
            continue

        key, value = line.split(":", 1)

        key = key.strip().lower().replace(" ", "_")
        value = value.strip()

        if value:
            result[key] = value

    return result


def safe_float(value):
    """Convert a value to float safely."""

    if value is None or value == "":
        return None

    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def safe_int(value):
    """Convert a value to int safely."""

    if value is None or value == "":
        return None

    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def flatten(value):
    """
    Flatten nested lists generated by normalizers.
    """

    if value is None:
        return []

    if isinstance(value, list):
        result = []

        for item in value:
            result.extend(flatten(item))

        return result

    return [value]


