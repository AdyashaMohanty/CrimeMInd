def normalize_email(
    source_file,
    content,
):
    if not isinstance(content, dict):
        return None

    sender = content.get("from")
    receiver = content.get("to")

    if sender and "@" in sender:
        sender = sender.split(
            "@",
            1
        )[0]

    if receiver and "@" in receiver:
        receiver = receiver.split(
            "@",
            1
        )[0]

    return {
        "communication": {
            "external_reference": content.get(
                "message_id"
            ),
            "type": "EMAIL",
            "sender": sender,
            "receiver": receiver,
            "start_time": content.get(
                "date"
            ),
            "duration_seconds": None,
            "status": None,
            "content": content.get(
                "body"
            ),
            "attributes": {
                "subject": content.get(
                    "subject"
                ),
                "cc": content.get(
                    "cc"
                ),
            },
        },
        "source_file": source_file,
    }


